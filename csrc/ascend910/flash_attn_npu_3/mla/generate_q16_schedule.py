#!/usr/bin/env python3
"""Generate the immutable Q16 schedule table from the production scheduler.

Run with --check to verify the checked-in table. Only scalar allocation geometry
and synthetic KV lengths enter the generator; no device or user data is read.
"""

import argparse
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parent
SURVEY = r"""
#include <array>
#include <cstring>
#include <iostream>
#include <stdexcept>
#include <vector>
#include "mla_tiling.cpp"
#include "mla_split.cpp"
#include "cann_split_core.cpp"
#include "mla_layout.cpp"
#include "mla_metadata.cpp"
using namespace flash_attn::mla;
struct Words {
    const uint32_t* data;
    uint32_t operator()(uint64_t word) const { return data[word]; }
};
struct Arrays {
    const int32_t* used;
    uint32_t operator()(uint32_t axis, uint32_t word) const { return axis == 3 ? used[word] : 0; }
};
int main()
{
    MlaContext c{1, 16, 8192, 128, 1, 0, 1, 20, 0, 1, 3, 0, 0, 128, 2, 512, 0, {1, 8191, 0}};
    MlaLayout allocation{};
    if (!MlaRecordLayout(c, allocation)) throw std::runtime_error("invalid allocation");
    c.workspaceBytes = allocation.bytes;
    std::vector<uint32_t> words(allocation.words);
    std::array<int32_t, 64> pages{};
    for (uint32_t i = 0; i < pages.size(); ++i) pages[i] = i;
    int32_t used = 0;
    MlaRecordArgs args{c, 0, 0, 0, reinterpret_cast<uint64_t>(&used),
                       reinterpret_cast<uint64_t>(words.data()), allocation.words};
    MlaPageTableView table{{1, 64}, {64, 1}, 0, 256};
    MlaBsndTensorView k{{64, 128, 1, 64}, {8192, 64, 64, 1}, 0, 1048576};
    MlaBsndTensorView v{{64, 128, 1, 512}, {65536, 512, 512, 1}, 0, 8388608};
    if (BuildPagedCacheLayout(table, k, v, args.cache.layout, false) != MlaLayoutStatus::Success)
        throw std::runtime_error("invalid cache");
    args.cache.table = {reinterpret_cast<uint64_t>(pages.data()), pages.size()};
    args.cache.k = {0x1000000000ULL, args.cache.layout.k.spanElements};
    args.cache.v = {0x2000000000ULL, args.cache.layout.v.spanElements};
    for (used = 0; used <= 8192; ++used) {
        MlaAutoSplitBsndSchedule schedule{};
        bool ready = false;
        if (!BuildMlaMetadata(args, &schedule, ready) || words[2] || !ready)
            throw std::runtime_error("metadata generation failed");
        MlaLayout layout{};
        MlaAutoSplitBsndSchedule checked{};
        const Words read{words.data()};
        if (ReadMlaMetadata(read, c, Arrays{&used}, layout, checked) != MlaMetadataReadStatus::Success ||
            ReadMlaPages(read, c, args.cache, Words{reinterpret_cast<const uint32_t*>(pages.data())}) !=
                MlaMetadataReadStatus::Success)
            throw std::runtime_error("invalid record");
        std::cout << '[' << words[22] << ',' << words[23];
        for (uint32_t i = 0; i < kMlaNativePartitionWords; ++i)
            std::cout << ',' << words[MlaTail(c) + i];
        std::cout << "]\n";
    }
}
"""

HEADER = """/**
 * Copyright (c) 2026 Huawei Technologies Co., Ltd.
 * Modified by Minghua Shen, 2026.
 *
 * Generated by generate_q16_schedule.py from the production CANN SplitCore
 * adapter. Every effective KV length 0..8192 is checked before packing.
 * Gate: physical20, B1/Q16/H128/HK1, KVcapacity8192, PA128, packed,
 * causal, splits0, margin0, no softcap, no Q-used, no supplied metadata.
 * The caller validates the current device length and all active pages before
 * lookup. These constants contain no user tensor contents or addresses.
 */
#pragma once
#include <cstdint>
namespace flash_attn::mla::detail {
struct MlaQ16PackedState { uint64_t word[10]; };
static_assert(sizeof(MlaQ16PackedState) == 80);
static constexpr MlaQ16PackedState kMlaQ16States[@STATES@] = {
@ROWS@
};
static constexpr uint32_t kMlaQ16IntervalEnds[@RUNS@] = {@ENDS@};
static constexpr uint32_t kMlaQ16IntervalIds[@RUNS@] = {@IDS@};
// Precondition: length <=8192, checked before numerical events/output stores.
__aicore__ inline MlaQ16PackedState LookupMlaQ16Schedule(uint32_t length)
{
    uint32_t first = 0, last = @RUNS@;
    while (first < last) {
        const uint32_t middle = first + (last - first) / 2;
        if (length > kMlaQ16IntervalEnds[middle])
            first = middle + 1;
        else
            last = middle;
    }
    return kMlaQ16States[kMlaQ16IntervalIds[first]];
}
} // namespace flash_attn::mla::detail
"""


def pack(key):
    m, n, *p = key
    assert m == 256 and n in (128, 256, 384, 512)
    control = n // 128 - 1 | p[3] << 2 | p[82] << 7 | p[83] << 11 | p[84] << 14
    ends = bytes((p[4 + i] << 7) | (p[30 + i] << 4) | p[56 + i] for i in range(20))
    starts = sum(p[164 + i] << (2 * i) for i in range(20))
    heads = sum((p[112 + i] | p[138 + i] << 3) << (6 * i) for i in range(8))
    vectors = bytes((p[242 + i] << 5) | p[294 + i] for i in range(40))
    raw = struct.pack("<I20sQQ40s", control, ends, starts, heads, vectors)
    # Reconstruct every native word, including implicit zeros, before accepting
    # the compressed representation. Scheduler changes must fail this check.
    c, e, s, h, v = struct.unpack("<I20sQQ40s", raw)
    q = [0] * 346
    q[:4] = [1, 8191, 0, (c >> 2) & 31]
    q[82:86] = [(c >> 7) & 15, (c >> 11) & 7, (c >> 14) & 63, 8]
    for i, x in enumerate(e):
        q[4 + i], q[30 + i], q[56 + i] = x >> 7, (x >> 4) & 7, x & 15
    for i in range(20):
        q[164 + i] = (s >> (2 * i)) & 3
    for i in range(8):
        x = (h >> (6 * i)) & 63
        q[112 + i], q[138 + i] = x & 7, x >> 3
    for i in range(q[82]):
        q[190 + i], q[216 + i] = 32, 8
    for i, x in enumerate(v):
        q[242 + i], q[294 + i] = x >> 5, x & 31
    assert [256, ((c & 3) + 1) * 128, *q] == key
    return struct.unpack("<10Q", raw)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cxx", default="g++")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="mla-q16-schedule-") as temporary:
        directory = Path(temporary)
        source, executable = directory / "survey.cpp", directory / "survey"
        source.write_text(SURVEY)
        subprocess.run(
            [args.cxx, "-O2", "-std=c++17", "-I", str(ROOT), str(source), "-o", str(executable)],
            check=True,
        )
        records = [
            json.loads(line)
            for line in subprocess.check_output([str(executable)], text=True).splitlines()
        ]
    assert len(records) == 8193
    ids, states, ends, mapping = {}, [], [], []
    for length, key in enumerate(records):
        state = ids.get(tuple(key))
        if state is None:
            state = len(states)
            ids[tuple(key)] = state
            states.append(pack(key))
        if mapping and mapping[-1] == state:
            ends[-1] = length
        else:
            mapping.append(state)
            ends.append(length)
    rows = ["    {{" + ", ".join(hex(x) + "ULL" for x in state) + "}}" for state in states]
    replacements = {
        "STATES": str(len(states)),
        "RUNS": str(len(ends)),
        "ROWS": ",\n".join(rows),
        "ENDS": ", ".join(map(str, ends)),
        "IDS": ", ".join(map(str, mapping)),
    }
    text = HEADER
    for token, value in replacements.items():
        text = text.replace("@" + token + "@", value)
    path = ROOT / "mla_q16_schedule.hpp"
    if args.check:
        assert re.sub(r"\s+", "", path.read_text()) == re.sub(r"\s+", "", text), (
            "Q16 table is stale"
        )
    else:
        path.write_text(text)
    print(f"Verified {len(records)} lengths, {len(states)} states, {len(ends)} intervals")


if __name__ == "__main__":
    main()
